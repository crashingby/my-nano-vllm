KB_bytes = 1_000
"""一个十进制千字节（KB）包含的字节数。"""

KiB_bytes = 1 << 10
"""一个二进制千字节（KiB）包含的字节数，即 2**10。"""

MB_bytes = 1_000_000
"""一个十进制兆字节（MB）包含的字节数。"""

MiB_bytes = 1 << 20
"""一个二进制兆字节（MiB）包含的字节数，即 2**20。"""

GB_bytes = 1_000_000_000
"""一个十进制吉字节（GB）包含的字节数。"""

GiB_bytes = 1 << 30
"""一个二进制吉字节（GiB）包含的字节数，即 2**30；Worker 显存日志使用此单位。"""
